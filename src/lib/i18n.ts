export function t(locale: Locale, key: string): string {
  return translations[locale]?.[key] || translations.en[key] || key;
}

/** Pick the Spanish variant when locale is "es" and es content exists, otherwise fallback to English */
export function localized(locale: Locale, en: string, es?: string | null): string {
  if (locale === "es" && es) return es;
  return en;
}

/** Same as localized but for string arrays (e.g. tips) */
export function localizedArray(locale: Locale, en: string[], es?: string[]): string[] {
  if (locale === "es" && es && es.length > 0) return es;
  return en;
}
